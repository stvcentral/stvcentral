import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const folder=mkdtempSync(join(tmpdir(),'royal-chaos-'));
process.env.CUSTOMER_DB_PATH=join(folder,'test.sqlite');
const store=await import('../lib/customerStore.mjs');
const {songs}=await import('../data/songs.js');

test('accounts, ownership, recovery and claim lifecycle',async()=>{
 const a=await store.register('collector_one','long-password-123'),b=await store.register('collector_two','another-password-123');
 await assert.rejects(store.register('COLLECTOR_ONE','different-password-123'),/unavailable/);
 await assert.rejects(store.login('collector_one','bad-password'),/incorrect/);
 assert.equal((await store.login('COLLECTOR_ONE','long-password-123')).id,a.user.id);
 const session=store.newSession(a.user);assert.equal(store.sessionUser(session).id,a.user.id);
 const booster=store.createClaims({kind:'booster',label:'Test booster',slugs:[songs[0].slug,songs[1].slug],count:1})[0];
 const claim=store.redeem(a.user,booster.code.toLowerCase());assert.equal(claim.added,2);
 assert.equal(store.redeem(a.user,booster.code).added,0);
 assert.throws(()=>store.redeem(b.user,booster.code),/another account/);
 assert.equal(store.collection(b.user).length,0);
 assert.equal(store.owns(a.user,songs[2].slug),false);
 assert.throws(()=>store.reveal(a.user,songs[2].slug),/Claim this card/);
 store.reveal(a.user,songs[0].slug);assert.ok(store.collection(a.user).find(s=>s.slug===songs[0].slug).revealed);
 const deck=store.createClaims({kind:'deck',label:'Full deck',count:1})[0];
 assert.equal(store.redeem(a.user,deck.code).added,52);assert.equal(store.collection(a.user).length,54);
 const single=store.createClaims({kind:'single',label:'Single',count:1,slugs:[songs[3].slug]})[0];
 assert.equal(store.redeem(b.user,single.code).added,1);
 assert.throws(()=>store.createClaims({kind:'single',label:'Invalid',count:1,slugs:[songs[0].slug,songs[1].slug]}),/exactly one/);
 const unused=store.createClaims({kind:'single',label:'Cancelled',count:1,slugs:[songs[4].slug]})[0];
 store.revokeClaim(store.digest(unused.code.replace(/[^A-Z0-9]/g,'')));
 assert.throws(()=>store.redeem(b.user,unused.code),/invalid/);
 await assert.rejects(store.recover('collector_one','wrong','new-long-password-123'),/incorrect/);
 const reset=await store.recover('collector_one',a.recovery,'new-long-password-123');
 assert.equal(store.sessionUser(session),null);
 await assert.rejects(store.login('collector_one','long-password-123'),/incorrect/);
 await assert.rejects(store.recover('collector_one',a.recovery,'another-new-password'),/incorrect/);
 assert.equal((await store.login('collector_one','new-long-password-123')).id,a.user.id);
 assert.notEqual(reset.recovery,a.recovery);
 assert.equal(store.collection(reset.user).length,54);
 const logoutSession=store.newSession(b.user);store.logout(logoutSession);assert.equal(store.sessionUser(logoutSession),null);
 for(let i=0;i<3;i++)store.limit('test-limit',3);assert.throws(()=>store.limit('test-limit',3),/Too many/);
 store.db().close();rmSync(folder,{recursive:true,force:true});
});
